import assert from "node:assert/strict";
import {freezeWildcardExperiment,gradeWildcards} from "../lib/wildcardprospective";
import type {ScenarioView} from "../lib/chipscenarioview";
import type {WildcardAlternative} from "../lib/wildcardalternatives";
import type {SimulatedPlayer} from "../lib/lineupsettlement";
const xi=Array.from({length:11},(_,i)=>({id:i+1,name:"P"+i,team:"A",pos:"MID",price:5,next:3,window:15,seasonPts:20,ppg:3,officialNext:3,elite:0}));
const bench=Array.from({length:4},(_,i)=>({...xi[i],id:i+12}));
const main={xi,bench,captainId:1,viceCaptainId:2} as ScenarioView;
const a=(criterion:"ppg"|"fpl"):WildcardAlternative=>({criterion,available:true,reason:"",ids:[...xi,...bench].map(p=>p.id),xiIds:xi.map(p=>p.id),xiNames:xi.map(p=>p.name),captainId:1,viceCaptainId:2,budgetRemaining:1,modelXiNext:33,modelXiWindow:165});
const deadline="2026-10-30T12:00:00Z",before=Date.parse("2026-10-29T12:00:00Z");
const snap=freezeWildcardExperiment(9,deadline,main,[a("ppg"),a("fpl")],before);
assert.ok(snap);assert.equal(snap.squads.length,3);
assert.equal(freezeWildcardExperiment(9,deadline,main,[a("ppg"),a("fpl")],Date.parse(deadline)),null);
assert.equal(freezeWildcardExperiment(9,deadline,main,[a("ppg")],before),null);
const actual=new Map<number,SimulatedPlayer>();
for(let i=1;i<=15;i++) actual.set(i,{id:i,position:i===1||i===12?1:i<=5||i===13?2:i<=9||i===14?3:4,minutes:90,points:2});
const settled=gradeWildcards(snap,actual,"2026-10-31T12:00:00Z");
assert.ok(settled);assert.equal(settled.results.length,3);
assert.equal(gradeWildcards(snap,actual,"2026-10-29T12:00:00Z"),null);
actual.delete(4);assert.equal(gradeWildcards(snap,actual,"2026-10-31T12:00:00Z"),null);
console.log("Wildcard prospective freeze and settlement integrity passed");
